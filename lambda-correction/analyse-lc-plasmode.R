# Lambda-correction on the plasmode cells: cell summaries and SUMMARY-plasmode.md from the
# task records of run-lc-plasmode.R (IJ and one-step arms; no jackknife or fixed-lambda).
# Run from the repository root:
#   Rscript lambda-correction/analyse-lc-plasmode.R <results_dir> <out_dir>
# Only aggregate scores are written (task files of the cardiology apps stay on LRZ).

LC_ANALYSE_LIB_ONLY <- TRUE
source("lambda-correction/analyse-lc.R")
source("plasmode/sources.R")
source("plasmode/plasmode.R")

LC_ARMS <- c(
  "cl2",
  "naive",
  "vc",
  "ij_lin",
  "ij_linx",
  "os_lin",
  "os_linx",
  "os_nl",
  "os_nlx"
)

args <- commandArgs(trailingOnly = TRUE)
if (length(args) < 2) stop("usage: analyse-lc-plasmode.R results_dir out_dir")
dir.create(args[2], recursive = TRUE, showWarnings = FALSE)
cells <- plasmode_cells()
cells <- cells[cells$app != "ecg_gls4", ]
# cell_keys() labels: family = app, error = truth:residual (+ block flips)
cells$family <- cells$app
cells$error <- paste0(
  cells$truth,
  ":",
  cells$residual,
  ifelse(cells$flip == "block", " block", "")
)
files_all <- list.files(args[1], "^task-c\\d+-r\\d+\\.rds$", full.names = TRUE)
out <- lapply(seq_len(nrow(cells)), \(i) {
  files <- grep(sprintf("task-c%03d-", cells$cell[i]), files_all, value = TRUE)
  if (!length(files)) return(NULL)
  summarise_cell(files, cells[i, ], abl_dir = tempfile())
})
out <- out[!vapply(out, is.null, TRUE)]
bind <- \(name) dplyr::bind_rows(lapply(out, `[[`, name))
res <- list(
  cells = bind("cells"),
  calib = bind("calib"),
  crn = bind("crn"),
  failures = bind("failures"),
  times = bind("times")
)
for (nm in names(res))
  write.csv(
    res[[nm]],
    file.path(args[2], paste0("lcp-", nm, ".csv")),
    row.names = FALSE
  )

arms <- c(
  cl2 = "CL2",
  naive = "+mgcv J",
  vc = "+mgcv Vc",
  ij_lin = "IJ",
  os_lin = "OS",
  os_nl = "OSnl",
  ij_linx = "IJ×",
  os_linx = "OS×"
)
by_app <- \(crit_, value, scale = 100) {
  res$cells |>
    dplyr::filter(crit == crit_, arm %in% names(arms)) |>
    dplyr::mutate(
      Gs = ifelse(G == PLASMODE_G_SMALL, "40", "all"),
      value = .data[[value]] * scale
    ) |>
    dplyr::group_by(estimand, family, Gs, arm) |>
    dplyr::summarise(value = mean(value), .groups = "drop") |>
    dplyr::mutate(arm = factor(arms[arm], arms)) |>
    tidyr::pivot_wider(names_from = arm, values_from = value) |>
    dplyr::select(
      estimand,
      app = family,
      G = Gs,
      dplyr::all_of(unname(arms))
    ) |>
    dplyr::arrange(
      factor(estimand, c("beta", "alpha", "gamma", "mean")),
      app,
      G
    )
}
rel_width <- res$cells |>
  dplyr::filter(crit == "z", arm %in% names(arms)) |>
  dplyr::group_by(cell, estimand) |>
  dplyr::mutate(value = width / width[arm == "cl2"]) |>
  dplyr::group_by(estimand, arm) |>
  dplyr::summarise(value = mean(value), .groups = "drop") |>
  dplyr::mutate(arm = factor(arms[arm], arms)) |>
  tidyr::pivot_wider(names_from = arm, values_from = value) |>
  dplyr::select(estimand, dplyr::all_of(unname(arms)))
md <- c(
  "# Lambda correction on the plasmode cells",
  "",
  "Generated by `lambda-correction/analyse-lc-plasmode.R`. Coverage (%) of nominal 95% pointwise",
  "intervals, grid-averaged, averaged over each app's cells (truth x residual sources) at",
  "G = all subjects and G = 40. Arms as in SUMMARY.md (no jackknife, no fixed-lambda arm).",
  "",
  sprintf(
    "- Task files: %d; failures: %d; replicates per cell %d to %d.",
    sum(vapply(out, `[[`, 0, "n_files")),
    nrow(res$failures),
    min(res$cells$n_rep),
    max(res$cells$n_rep)
  ),
  sprintf(
    "- CRN vs plasmode records: max relative difference est %.1e, CL2 SE %.1e.",
    max(res$crn$max_rel[res$crn$column == "est_REML"]),
    max(res$crn$max_rel[res$crn$column == "se_cl2"])
  ),
  sprintf(
    "- Time per task: median %.1f s, total %.1f core-hours.",
    median(res$times$total),
    sum(res$times$total) / 3600
  ),
  "",
  "## Coverage, z",
  "",
  md_table(by_app("z", "coverage")),
  "## Coverage, t_{G-1}",
  "",
  md_table(by_app("t", "coverage")),
  "## SE/SD",
  "",
  md_table(by_app("z", "se_sd_ratio", 1), 2),
  "## Width relative to CL2 (mean over cells), z",
  "",
  md_table(rel_width, 3)
)
writeLines(md, file.path(args[2], "SUMMARY-plasmode.md"))
cat("wrote", file.path(args[2], "SUMMARY-plasmode.md"), "\n")
