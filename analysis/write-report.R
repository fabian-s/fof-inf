# Results report from the tables written by run-analysis.R. Every number in the report
# comes from those tables. Run from the repository root:
#   Rscript analysis/write-report.R <summaries dir>
source("scripts/setup.R")
suppressPackageStartupMessages(library(dplyr))
dir <- commandArgs(trailingOnly = TRUE)[1]
read <- \(name)
  readr::read_csv(file.path(dir, paste0(name, ".csv")), show_col_types = FALSE)
cell_summaries <- read("cells")
# The design as saved with the results (cell ids of that run), not the current table.
cells <- cell_summaries |>
  select(
    cell,
