fits <- read("fit-diagnostics")

md_table <- function(df, digits = 3) {
  df <- mutate(
    df,
    across(
      where(\(x) is.numeric(x) && any(x != round(x), na.rm = TRUE)),
      \(x) formatC(x, digits = digits, format = "f")
    )
  )
  header <- paste("|", paste(names(df), collapse = " | "), "|")
  rule <- paste("|", paste(rep("---", ncol(df)), collapse = " | "), "|")
  rows <- apply(df, 1, \(r) paste("|", paste(r, collapse = " | "), "|"))
  paste(c(header, rule, rows), collapse = "\n")
}
section <- \(title, ...)
  cat("\n## ", title, "\n\n", paste(..., sep = "\n\n"), "\n", sep = "")
ci <- \(est, lo, hi, d = 3)
  sprintf(paste0("%.", d, "f [%.", d, "f, %.", d, "f]"), est, lo, hi)
coverage_wide <- function(filter_expr, estimands = c("mean", "beta"), arms) {
  cell_summaries |>
    filter({{ filter_expr }}, estimand %in% estimands, arm %in% arms) |>
    select(
      cell,
      family,
      fit_family,
      error,
      G,
      signal,
      truth,
      estimand,
      arm,
      coverage_mean
    ) |>
    tidyr::pivot_wider(names_from = arm, values_from = coverage_mean)
}

