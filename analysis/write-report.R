# Question 9: basis size (only once the basis-size block has results) ----------------------

basis_run <- any(
  cell_summaries$block == "basis_size" & !is.na(cell_summaries$n_rep)
)
if (basis_run) {
  sized <- cells$block == "basis_size"
  default_core <- cells$block == "core" &
    cells$G == 100 &
    cells$signal == "mid" &
    paste(cells$family, cells$error) %in%
      paste(cells$family[sized], cells$error[sized])
  basis_cells <- cells[sized | default_core, ]
  basis_levels <- names(BASES) # default, large, xlarge
  by_basis <- \(df) {
    df |>
      mutate(basis = factor(basis, basis_levels)) |>
      arrange(basis)
  }
  section(
    "Question 9: basis size (nested bases; large/xlarge halve/quarter the knot spacing of the default), G = 100, mid signal, smooth truth",
    "MSE_NCV / MSE_REML per basis:",
    md_table(
      read("within-cell-contrasts") |>
        filter(contrast == "ncv vs reml: squared error") |>
        inner_join(basis_cells, by = "cell") |>
        by_basis() |>
        transmute(
          family,
          error,
          estimand,
          basis,
          ratio = ci(ratio, ratio_lower, ratio_upper, 2)
        ) |>
        tidyr::pivot_wider(names_from = basis, values_from = ratio) |>
        arrange(family, error, estimand)
    ),
    "Coverage (nominal 0.95) and interval score:",
    md_table(
      cell_summaries |>
        inner_join(basis_cells["cell"], by = "cell") |>
        filter(
          estimand %in% c("mean", "beta"),
          arm %in% c("reml_model", "reml_cl2", "ncv_cl2", "ncv_cl2_bias")
        ) |>
        by_basis() |>
        select(
          family,
          error,
          estimand,
          basis,
          arm,
          coverage_mean,
          score_mean
        ) |>
        arrange(family, error, estimand, basis, arm)
    ),
    "Large/xlarge minus the default-basis core cell (coverage differences; log_* are log ratios large/default, log_mse_ratio_ncv_reml the log ratio of ratios):",
    md_table(
      read("matched-contrasts") |>
        inner_join(cells[sized, ], by = "cell") |>
        transmute(
          family,
          error,
          basis,
          estimand,
          value,
          diff = ci(estimate, lower, upper)
        ) |>
        tidyr::pivot_wider(names_from = value, values_from = diff) |>
        arrange(family, error, estimand, basis)
    ),
    "Mean EDF per term (REML and NCV fits):",
    md_table(
      read("term-edf") |>
        inner_join(basis_cells, by = "cell") |>
        filter(fit %in% c("REML", "NCV")) |>
        by_basis() |>
        transmute(family, error, fit, term, basis, edf = edf_mean) |>
        tidyr::pivot_wider(names_from = basis, values_from = edf) |>
        arrange(family, error, term, fit),
      digits = 1
    )
  )
}
